const fs = require('node:fs/promises');
const path = require('node:path');
const {spawnSync} = require('node:child_process');
module.exports = async function afterSign(context) {
  if (context.electronPlatformName !== 'mas') return;
  const app = path.join(context.appOutDir, `${context.packager.appInfo.productFilename}.app`);
  const cli = path.join(app, 'Contents/Resources/codex');
  const identity = process.env.TWH_MAS_SIGNING_IDENTITY;
  const entitlements = process.env.TWH_MAS_ENTITLEMENTS;
  const inherit = process.env.TWH_MAS_CODEX_ENTITLEMENTS;
  if (!identity || !entitlements || !inherit) throw new Error('缺少 MAS Codex 签名参数');
  function run(command, args) { const result=spawnSync(command,args,{encoding:'utf8'}); if(result.status!==0) throw new Error(`${command} failed: ${result.stderr}`); return result.stdout; }
  async function visit(dir) {
    for (const entry of await fs.readdir(dir, {withFileTypes:true})) {
      const file=path.join(dir,entry.name);
      if(entry.isSymbolicLink()) continue;
      if(entry.isDirectory()) await visit(file);
      else if(run('/usr/bin/file',['-b',file]).includes('Mach-O')) {
        // CLI helpers inherit their containing app's sandbox. Unlike Electron
        // V8 helpers, these use precisely Apple's two inheritance entitlements.
        run('/usr/bin/codesign',['--force','--sign',identity,'--entitlements',inherit,file]);
      }
    }
  }
  const parentEntitlements = run('/usr/bin/codesign',['-d','--entitlements',':-',app]);
  if (!parentEntitlements.includes('com.apple.security.app-sandbox')) throw new Error('母应用缺少沙盒权限');
  const preserved = path.join(context.appOutDir, 'parent-entitlements.plist');
  await fs.writeFile(preserved, parentEntitlements, {mode:0o600});
  await visit(cli);
  // Preserve the identifiers/keychain entitlements generated by Electron's
  // signer, rather than replacing them with our pre-signing input plist.
  run('/usr/bin/codesign',['--force','--sign',identity,'--entitlements',preserved,app]);
  run('/usr/bin/codesign',['--verify','--deep','--strict',app]);
};
