import { chromium, expect } from '@playwright/test';
import { createRequire } from 'node:module';
import { writeFile, rm, mkdir, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const studio = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const web = path.join(studio, 'apps/web');
const require = createRequire(path.join(web, 'package.json'));
const { createServer } = await import(require.resolve('vite'));
const fixtureName = `.source-directories-${process.pid}`;
const fixture = path.join(web, `${fixtureName}.tsx`);
const html = path.join(web, `${fixtureName}.html`);
const captures = path.join(studio, '.impeccable/reviews/source-directories');
let server, browser;
try {
  await mkdir(captures, { recursive: true });
  await writeFile(fixture, `import React from 'react';
import {createRoot} from 'react-dom/client';
import {MemoryRouter} from 'react-router-dom';
import {EditableDocument, ReadOnlyDocument} from './src/shared/markdown';
import {ImportMaterialsModal} from './src/features/sources/ImportMaterialsModal';
import './src/features/sources/source-connections.css';
${['theme-tokens','base','form-controls','features','archive-foundation','refinements','archive-theme','sources-redesign','desktop','desktop-redesign'].map(name => `import './src/styles/${name}.css';`).join('\n')}
import './src/shared/document.css';
const params = new URLSearchParams(location.search);
const markdown = params.has('diary') ? '# 匿名文档\\n\\n第一段匿名日记。\\n\\n第二段匿名日记。' : '# 匿名文档\\n\\n' + ['第一节','第二节','第三节'].map(title => '## '+title+'\\n\\n'+Array.from({length:10},(_,i)=>title+'的第'+(i+1)+'段。这是一段用于验证阅读和编辑连续性的匿名文字。保留相同的字体、宽度和正文位置。').join('\\n\\n')).join('\\n\\n');
const page = {id:'demo-document',title:'匿名文档',relativePath:'sources/匿名文档.md',...(params.has('external') ? {externalSource:{connectionId:'local',originalPath:'/anonymous/日记/2026/匿名文档.md',originalRelativePath:'2026/匿名文档.md',status:'available'}} : {}),modifiedAt:'2026-10-10T00:00:00Z',isSource:true,markdown,renderedMarkdown:markdown,properties:{},tags:[],aliases:[],locations:[],sources:[],sections:[],outgoingLinks:[],incomingLinks:[],category:'sources',excerpt:''};
createRoot(document.getElementById('root')).render(<MemoryRouter><div className="desktop-shell organized-sources-page" style={{display:'block',height:'100vh',padding:20}}><main id="main-content" style={{height:'100%',overflowY:'auto'}}><div className="source-vault" style={{display:"block"}}><article className="source-preview">{params.has('import') ? <ImportMaterialsModal folders={['聊天记录','聊天记录/2026']} currentFolder='' onClose={()=>{}} onImported={()=>{}} onConnected={()=>{}} onJourney={()=>{}} /> : params.has('readonly') ? <ReadOnlyDocument page={page} id={page.id} markdown={markdown}/> : <EditableDocument page={page} variant="preview" relations={params.has('diary') ? undefined : <p>匿名来源与关联</p>} />}</article></div></main></div></MemoryRouter>);
`);
  await writeFile(html, `<html><meta charset="utf-8"><div id="root"></div><script type="module" src="/${fixtureName}.tsx"></script></html>`);
  server = await createServer({ root: web, server: { host: '127.0.0.1', port: 0, strictPort: false, open: false }, logLevel: 'error' });
  await server.listen();
  const origin = `http://127.0.0.1:${server.httpServer.address().port}/${fixtureName}.html`;
  const chromeInstalled = await access('/Applications/Google Chrome.app').then(() => true, () => false);
  browser = await chromium.launch({ headless: true, ...(chromeInstalled ? {channel:'chrome'} : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  let writes = 0;
  await page.route('**/api/pages/**', route => { writes++; return route.fulfill({json:{ok:true,modifiedAt:'2026-10-10T01:00:00Z'}}); });
  await page.route('**/api/vault', route => route.fulfill({json:{knowledgeBaseId:'demo'}}));
  await page.route('**/api/source-connections', route => route.fulfill({json:[]}));
  const geometry = selector => page.locator(selector).evaluate(node => {const r=node.getBoundingClientRect(), s=getComputedStyle(node);return {x:r.x,width:r.width,font:s.font,color:s.color,padding:s.padding};});
  for (const width of [1440, 820]) {
    await page.setViewportSize({width,height:1000});
    await page.goto(origin);
    const body = page.locator('.editable-document-body');
    await expect(body).toBeVisible();
    const reading = await geometry('.editable-document-body');
    const title = await page.locator('.editable-document-identity').boundingBox();
    await page.screenshot({animations:'disabled',path:path.join(captures,`${width}-reading.png`)});
    await page.getByRole('button',{name:'展开文档导航',exact:true}).click();
    const opened = await geometry('.editable-document-body');
    await expect(page.locator('.document-outline-panel')).toHaveCSS('width', '220px');
    const navigationBox = await page.locator('.document-outline-panel').boundingBox();
    expect(navigationBox.width).toBe(220);
    await page.locator('.editable-document-activate').dblclick();
    const editor = page.locator('.document-editor');
    await expect(editor).toBeVisible();
    const editing = await geometry('.document-editor');
    expect(editing).toEqual(opened);
    const editTitle = await page.locator('.editable-document-identity').boundingBox();
    expect(editTitle.width).toBe(title.width);
    await page.screenshot({animations:'disabled',path:path.join(captures,`${width}-editing.png`)});
    // Clicking navigation does not leave edit mode; its source heading gets selected.
    await page.getByRole('link',{name:'第二节',exact:true}).click();
    await expect(editor).toBeVisible();
    expect(await editor.evaluate(node => node.value.slice(node.selectionStart).startsWith('## 第二节'))).toBe(true);
    await editor.press('Escape');
    await expect(body).toBeVisible();
    const heading = page.getByRole('heading',{name:'第二节',exact:true});
    expect((await heading.boundingBox()).y).toBeLessThan(180);
    await page.getByRole('button',{name:'收起文档导航',exact:true}).click();
    await page.locator('.editable-document-activate').dblclick();
    await editor.fill((await editor.inputValue())+'\\n新增匿名正文');
    await page.getByRole('button',{name:'展开文档导航',exact:true}).click();
    await expect(editor).toBeVisible();
    await page.waitForTimeout(1000);
    expect(writes).toBeGreaterThan(0);
    expect(reading.width).toBeLessThanOrEqual(720);
    expect(reading.width).toBeGreaterThan(500);
  }
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(origin+'?readonly');
  await expect(page.getByRole('button',{name:'编辑',exact:true})).toHaveCount(0);
  await expect(page.locator('.editable-document-body')).toBeVisible();
  expect(await geometry('.editable-document-body')).toMatchObject({width:720});
  await page.goto(origin+'?diary');
  await expect(page.locator('.document-outline-panel')).toHaveCount(0);
  const diaryReading = await geometry('.editable-document-body');
  await page.locator('.editable-document-activate').dblclick();
  expect(await geometry('.document-editor')).toEqual(diaryReading);
  await page.setViewportSize({width:820,height:1000});
  await expect.poll(() => page.locator('.document-editor').evaluate(node => node.clientHeight >= node.scrollHeight)).toBe(true);
  expect(errors).toEqual([]);
  await page.goto(origin+'?external');
  await expect(page.getByRole('button',{name:'阅读',exact:true})).toHaveCount(0);
  await expect(page.getByRole('button',{name:'编辑',exact:true})).toHaveCount(0);
  await page.locator('.editable-document-activate').dblclick();
  await expect(page.locator('.document-editor')).toBeVisible();
  await page.locator('.document-editor').fill('修改本地日记');
  await page.locator('.document-editor').press('Escape');
  await expect(page.locator('.editable-document-body')).toContainText('修改本地日记');
  await page.goto(origin+'?import');
  await expect(page.getByRole('button',{name:'打开文件夹',exact:true})).toBeVisible();
  await expect(page.locator('input[name="import-files"]')).toHaveCount(0);
  await expect(page.getByRole('button',{name:'下一步'})).toHaveCount(0);
  await page.screenshot({animations:'disabled',path:path.join(captures,'open-folder.png')});
  await page.getByRole('button',{name:'聊天记录',exact:true}).click();
  await expect(page.locator('input[name="import-files"]')).toHaveCount(1);
  await expect(page.getByRole('button',{name:'下一步'})).toBeDisabled();
  expect(errors).toEqual([]);
  console.log('Source directory UI passed; document continuity passed: wide/narrow geometry, heading navigation while editing, Escape restoration, autosave, read-only layout, no-heading diary and editor resize.');
} finally {
  await browser?.close();
  await server?.close();
  await Promise.all([rm(fixture,{force:true}),rm(html,{force:true})]);
}
