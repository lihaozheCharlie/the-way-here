import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { cp, mkdir, mkdtemp, readFile, realpath, rm, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import os from "node:os";
import path from "node:path";
import Fastify from "fastify";
import { afterEach, describe, expect, it, vi } from "vitest";
import { stateRootForVault } from "@the-way-here/run-manager";
import { KnowledgeRuntime } from "./knowledge-runtime.js";
import { RunCoordinator } from "./run-coordinator.js";
import { registerPredictionRoutes } from "../routes/prediction-routes.js";
import type { AgentRuntimeEnvelope, AgentRuntimeProvider } from "./agent-runtime/types.js";
import { PredictionService } from "./prediction-service.js";
const cleanups: Array<() => Promise<void>> = [];
afterEach(async () => { for (const cleanup of cleanups.splice(0)) await cleanup(); });
const fullReport = JSON.parse(readFileSync(new URL("../../../../test/fixtures/life-prediction.json",import.meta.url),"utf8"));
const report = JSON.stringify({...fullReport,evidence:[],scenarios:[]});
async function fixture() {
  const root = await realpath(await mkdtemp(path.join(os.tmpdir(), "twh-predict-")));
  await writeFile(path.join(root, "the-way-here.config.yaml"), "version: 3\ndefaultKnowledgeBase: demo\nknowledgeBases:\n  demo:\n    paths:\n      wiki: demo/wiki\n      sources: demo/sources\n  other:\n    paths:\n      wiki: other/wiki\n      sources: other/sources\nvalidation:\n  commands: []\n");
  await cp(fileURLToPath(new URL("../../../../../knowledge-engine/skills/consume/predict-self", import.meta.url)), path.join(root, "knowledge-engine/skills/consume/predict-self"), { recursive: true });
  await mkdir(path.join(root, "demo/sources"), {recursive:true});
  const folders = ["01 个人主线", "02 人生阶段", "03 关键事件与决策", "04 反复循环", "06 现实系统", "11 状态追踪"];
  for (let i = 0; i < 12; i++) {
    await writeFile(path.join(root, `demo/sources/s${i}.md`), `---\nStart: ${i === 0 ? "2024-01-01" : "2026-09-01"}\n---\n# 记录 ${i}\n${"匿名用户描述了真实选择及其后果。".repeat(15)}`);
    const folder = `demo/wiki/${folders[i % folders.length]}`;
    await mkdir(path.join(root, folder), {recursive:true});
    await writeFile(path.join(root, folder, `p${i}.md`), `# 理解 ${i}\n${"一次具体选择与复盘结论。".repeat(15)}\n[[demo/sources/s${i}]]`);
  }
  const stateFile = path.join(stateRootForVault(root), "predictions", createHash("sha256").update("demo").digest("hex"), "state.json");
  await mkdir(path.dirname(stateFile),{recursive:true});
  await writeFile(stateFile,JSON.stringify({knowledgeBaseId:"demo",status:"idle",assessment:{version:2,score:75,threshold:60,unlocked:true,facets:[]},assessedAt:"2026-09-01T00:00:00Z"}));
  const knowledge = await KnowledgeRuntime.create(root, "demo");
  const listeners = new Set<(e: AgentRuntimeEnvelope) => void>();
  let seq = 0;
  const start = vi.fn(async () => ({runtimeId: "codex" as const, sessionId: `session${++seq}`, turnId: "turn"}));
  const runtime = { start, recover: vi.fn(async () => ({status:"completed", finalAnswer: report})), interrupt: vi.fn(), decide: vi.fn() };
  const provider = { subscribe: (fn: (e: AgentRuntimeEnvelope) => void) => {listeners.add(fn); return () => listeners.delete(fn);}, resolve: async () => ({runtime, runtimeId:"codex", model:{id:"test"}, effort:"high"}), require: () => runtime, close: vi.fn() } as unknown as AgentRuntimeProvider;
  const app = Fastify();
  const service = new PredictionService(knowledge, provider, app.log);
  registerPredictionRoutes(app, knowledge, service);
  const finish = (session = seq, text = report) => { for(const listener of listeners) listener({ref:{runtimeId:"codex",sessionId:`session${session}`,turnId:"turn"}, event:{type:"turn.completed",outcome:"completed",finalAnswer:text}}); };
  cleanups.push(async () => {service.close(); await app.close(); await knowledge.close(); await rm(root,{recursive:true,force:true}); await rm(stateRootForVault(root),{recursive:true,force:true});});
  return { root, knowledge, provider, app, service, start, finish, runtime };
}
describe("prediction lifecycle", () => {
  it("makes evidence beyond the preview readable and validates its full frozen quote", async () => {
    const {root, service, start, finish, knowledge} = await fixture();
    const quote = "我想将来回到小城与父母常常见面，这是我自己的愿望。";
    await writeFile(path.join(root, "demo/sources/old.md"), `---\nStart: 2010-01-01\n---\n${"早期普通记录。".repeat(1200)}\n${quote}`);
    await mkdir(path.join(root, "other/sources"), {recursive:true});
    await writeFile(path.join(root, "other/sources/private.md"), "不属于这个知识库的愿望资料");
    await service.request("demo");
    const input = (start.mock.calls as unknown as Array<[{prompt:string}]>)[0]![0];
    expect(input.prompt).not.toContain(quote);
    const file = path.join(stateRootForVault(root), "predictions", createHash("sha256").update("demo").digest("hex"), "evidence.json");
    expect(input.prompt).toContain(JSON.stringify(file));
    const frozen = JSON.parse(await readFile(file, "utf8"));
    expect(frozen.knowledgeBaseId).toBe("demo");
    expect(JSON.stringify(frozen)).not.toContain("不属于这个知识库的愿望资料");
    const oldPage = frozen.pages.find((p: any) => p.markdown.includes(quote));
    expect(oldPage).toBeDefined();
    expect(frozen.catalogue.some((p: any) => p.pageId === oldPage.pageId)).toBe(true);
    expect(frozen.lifeSearch.scanned.sources).toBeGreaterThan(0);
    expect(frozen.lifeSearch.scanned.wiki).toBeGreaterThan(0);
    expect(frozen.lifeSearch.hits.some((hit: any) => hit.pageId === oldPage.pageId)).toBe(true);
    expect(input.prompt).toContain("生活关键词全文搜索已经完成");
    await knowledge.activate("other");
    const result = structuredClone(fullReport);
    result.evidence[0].pageId = oldPage.pageId;
    result.evidence[0].quote = quote;
    finish(1, JSON.stringify(result));
    await vi.waitFor(async () => expect((await service.view("demo")).status).toBe("ready"));
    const saved = (await service.view("demo")).report;
    expect(saved?.version === 5 && saved.evidence[0]?.quote).toBe(quote);
    expect((await service.view("other")).report).toBeUndefined();
  });
  it("requires a scan rather than thoughts and runs scans without prediction", async () => {
    const {app,service,start,finish}=await fixture();
    expect((await app.inject({method:"POST",url:"/api/predictions/refresh",payload:{knowledgeBaseId:"other",thoughts:"当前想法".repeat(40)}})).statusCode).toBe(409);
    expect(start).not.toHaveBeenCalled();
    expect((await app.inject({method:"POST",url:"/api/predictions/scan",payload:{knowledgeBaseId:"other"}})).statusCode).toBe(202);
    await vi.waitFor(()=>expect(start).toHaveBeenCalledTimes(1));
    expect((await service.view("other")).understanding.scanStatus).toBe("running");
    const zero={version:2,facets:["health","work","play","love"].map(id=>({id,level:0,reason:"Wiki 中没有这一维度的信息",gaps:["补充具体经历"],evidence:[]}))};
    finish(1,JSON.stringify(zero));
    await vi.waitFor(async()=>expect((await service.view("other")).understanding.scanStatus).toBe("ready"));
    expect((await service.view("other")).understanding).toMatchObject({score:0,unlocked:false});
    expect((await service.view("other")).report).toBeUndefined();
    expect(start).toHaveBeenCalledTimes(1);
    await service.scan("other");
    finish(2,"invalid");
    await vi.waitFor(async()=>expect((await service.view("other")).understanding.scanStatus).toBe("failed"));
    expect((await service.view("other")).understanding.score).toBe(0);
  });
  it("separates hypothetical input, rejects invalid kinds and forgets withdrawn context", async () => {
    const {app,root,service,start,finish}=await fixture();
    expect((await app.inject({method:"POST",url:"/api/predictions/refresh",payload:{knowledgeBaseId:"demo",thoughtKind:"invalid"}})).statusCode).toBe(400);
    const thoughts="如果我搬到海边生活，保留目前的远程工作呢？";
    await service.request("demo",thoughts,"hypothesis");
    const result=JSON.parse(report);
    result.evidence=[{...fullReport.evidence[0],pageId:"prediction-input/current",quote:thoughts,kind:"hypothesis"}];
    finish(1,JSON.stringify(result));
    await vi.waitFor(async()=>expect((await service.view("demo")).status).toBe("ready"));
    expect((await service.view("demo")).thoughtKind).toBe("hypothesis");
    await service.request("demo","","update");
    const input=(start.mock.calls as unknown as Array<[{prompt:string}]>)[1]![0];
    expect(input.prompt).not.toContain(thoughts);
    const file=path.join(stateRootForVault(root),"predictions",createHash("sha256").update("demo").digest("hex"),"evidence.json");
    expect(await readFile(file,"utf8")).not.toContain(thoughts);
    finish(2);
    await vi.waitFor(async()=>expect((await service.view("demo")).status).toBe("ready"));
    expect((await service.view("demo")).thoughts).toBe("");
  });
  it("rejects locked libraries and invalid IDs at the HTTP boundary", async () => {
    const {app, start} = await fixture();
    expect((await app.inject({method:"POST",url:"/api/predictions/refresh",payload:{knowledgeBaseId:"other"}})).statusCode).toBe(409);
    expect((await app.inject({method:"GET",url:"/api/predictions?knowledgeBaseId=../../etc"})).statusCode).toBe(400);
    expect(start).not.toHaveBeenCalled();
  });
  it("deduplicates manual refresh, keeps the bound library, and persists across restart", async () => {
    const {knowledge, service, start, finish, provider, app} = await fixture();
    expect((await service.view("demo")).understanding.unlocked).toBe(true);
    await Promise.all([service.request("demo"),service.request("demo")]);
    expect(start).toHaveBeenCalledTimes(1);
    expect(start.mock.calls[0]).toBeDefined();
    await knowledge.activate("other");
    finish();
    await vi.waitFor(async () => expect((await service.view("demo")).status).toBe("ready"));
    expect((await service.view("other")).report).toBeUndefined();
    service.close();
    const restarted = new PredictionService(knowledge,provider,app.log);
    expect((await restarted.view("demo")).report?.summary).toBe("匿名情景");
    restarted.close();
  });
  it("keeps a v1 report on disk but never exposes its five-tab presentation", async () => {
    const {root,service,finish} = await fixture();
    await service.request("demo"); finish();
    await vi.waitFor(async () => expect((await service.view("demo")).status).toBe("ready"));
    const file = path.join(stateRootForVault(root), "predictions", createHash("sha256").update("demo").digest("hex"), "state.json");
    const state = JSON.parse(await readFile(file, "utf8")); state.report.version = 1;
    await writeFile(file, JSON.stringify(state));
    const old = await service.view("demo");
    expect(old).toMatchObject({status:"idle", stale:true});
    expect(old.report).toBeUndefined();
    expect(JSON.parse(await readFile(file, "utf8")).report.version).toBe(1);
  });
  it("does not rerun when Wiki changes during prediction; waits for another manual request", async () => {
    const {root,service,start,finish,app} = await fixture();
    await service.request("demo"); finish(1);
    await vi.waitFor(async () => expect((await service.view("demo")).status).toBe("ready"));
    await service.request("demo");
    await writeFile(path.join(root,"demo/wiki/new.md"),"# 新的理解\n一次新的具体选择。");
    finish(2);
    await vi.waitFor(async () => expect((await service.view("demo")).status).toBe("failed"));
    expect(start).toHaveBeenCalledTimes(2);
    expect(await service.view("demo")).toMatchObject({stale:true,report:{summary:"匿名情景"}});
    expect((await service.view("demo")).error).toContain("Wiki 已更新");
    const response = await app.inject({method:"POST",url:"/api/predictions/refresh",payload:{knowledgeBaseId:"demo"}});
    expect(response.statusCode).toBe(202);
    await vi.waitFor(() => expect(start).toHaveBeenCalledTimes(3));
    finish(3);
    await vi.waitFor(async () => expect((await service.view("demo")).status).toBe("ready"));
  });
  it("ignores legacy automatic pending jobs on restart", async () => {
    const {root,service,provider,knowledge,app,start} = await fixture();
    const file = path.join(stateRootForVault(root), "predictions", createHash("sha256").update("demo").digest("hex"), "state.json");
    await mkdir(path.dirname(file), {recursive:true});
    await writeFile(file, JSON.stringify({knowledgeBaseId:"demo",status:"idle",pending:true}));
    service.close();
    const restarted = new PredictionService(knowledge,provider,app.log);
    await restarted.reconcile();
    expect(start).not.toHaveBeenCalled();
    expect((await restarted.view("demo")).status).toBe("locked");
    restarted.close();
  });
  it("retains a previous report when invalid output fails validation", async () => {
    const {service,finish} = await fixture();
    await service.request("demo");finish();
    await vi.waitFor(async () => expect((await service.view("demo")).status).toBe("ready"));
    await service.request("demo");finish(2,"{broken}");
    await vi.waitFor(async () => expect((await service.view("demo")).status).toBe("failed"));
    expect((await service.view("demo")).report?.summary).toBe("匿名情景");
  });
  it("captures a completion emitted before start returns its session reference", async () => {
    const {service,start,finish} = await fixture();
    start.mockImplementationOnce(async () => { finish(1); return { runtimeId: "codex", sessionId: "session1", turnId: "turn" }; });
    await service.request("demo");
    await vi.waitFor(async () => expect((await service.view("demo")).status).toBe("ready"));
  });
  it("does not trigger prediction when build quality validation fails", async () => {
    const {provider,knowledge,app,finish,root,service,start} = await fixture();
    const file = path.join(root, "the-way-here.config.yaml");
    await writeFile(file, (await readFile(file, "utf8")).replace("commands: []", 'commands: [["node", "-e", "process.exit(1)"]]'));
    await knowledge.index.rebuild();
    const coordinator = new RunCoordinator(knowledge,provider,app.log);
    const run = await coordinator.start({knowledgeBaseId:"demo",mode:"write",prompt:"构建"});
    finish(1,"完成");
    await vi.waitFor(async () => expect((await coordinator.get(run.id))?.status).toBe("failed"));
    expect(start).toHaveBeenCalledTimes(1);
    expect((await service.view("demo")).status).toBe("idle");
    coordinator.close();
  });
  it("recovers a completed background thread after a service restart", async () => {
    const {service,provider,knowledge,app,runtime} = await fixture();
    await service.request("demo");service.close();
    const restarted = new PredictionService(knowledge,provider,app.log);
    await restarted.reconcile();
    expect(runtime.recover).toHaveBeenCalled();
    expect((await restarted.view("demo")).status).toBe("ready");
    restarted.close();
  });
  it.each(["write", "auto", "read"] as const)("%s completion leaves prediction idle until the page API is called", async (mode) => {
    const {service,provider,knowledge,app,finish,root,start} = await fixture();
    const coordinator = new RunCoordinator(knowledge,provider,app.log);
    const run = await coordinator.start({knowledgeBaseId:"demo",mode,prompt:"构建匿名 Wiki"});
    if (mode !== "read") await writeFile(path.join(root,"demo/wiki/new-build.md"), "# 构建的新内容\n新增的匿名理解。");
    finish(1,"构建完成");
    await vi.waitFor(async () => expect((await coordinator.get(run.id))?.status).toBe("completed"));
    expect(start).toHaveBeenCalledTimes(1);
    expect((await service.view("demo")).status).toBe("idle");
    // Merely visiting the unlocked page must not start a prediction either.
    expect((await app.inject({method:"GET",url:"/api/predictions?knowledgeBaseId=demo"})).statusCode).toBe(200);
    expect(start).toHaveBeenCalledTimes(1);
    const response = await app.inject({method:"POST",url:"/api/predictions/refresh",payload:{knowledgeBaseId:"demo"}});
    expect(response.statusCode).toBe(202);
    await vi.waitFor(() => expect(start).toHaveBeenCalledTimes(2));
    finish(2);
    await vi.waitFor(async () => expect((await service.view("demo")).status).toBe("ready"));
    coordinator.close();
  });
});
