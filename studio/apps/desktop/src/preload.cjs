const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('desktop', {
  platform: process.platform,
  isMacAppStore: process.argv.includes('--twh-mas'),
  connectCodexCLI: () => ipcRenderer.invoke('desktop:connect-codex'),
  openPrivacy: () => ipcRenderer.invoke('desktop:privacy'),
  photoLibraryStatus: () => ipcRenderer.invoke('desktop:photos-status'),
  photoLibraryFilters: () => ipcRenderer.invoke('desktop:photos-filters'),
  authorizePhotoLibrary: () => ipcRenderer.invoke('desktop:photos-authorize'),
  searchPhotoLibrary: (input) => ipcRenderer.invoke('desktop:photos-search', input),
  photoLibraryImage: (input) => ipcRenderer.invoke('desktop:photos-image', input),
  cancelPhotoLibrarySearch: () => ipcRenderer.invoke('desktop:photos-cancel'),
  retainPhotoLibrary: (input) => ipcRenderer.invoke('desktop:photos-retain', input),
  exportPhotoLibrary: (input) => ipcRenderer.invoke('desktop:photos-export', input),
  closePhotoLibrary: () => ipcRenderer.invoke('desktop:photos-close'),
  openPhotoLibrarySettings: () => ipcRenderer.invoke('desktop:photos-settings'),
  pathForDroppedFile: (file) => webUtils.getPathForFile(file),
  requestFolderAccess: () => ipcRenderer.invoke('desktop:folder-permission'),
  chooseSourceDirectory: () => ipcRenderer.invoke('desktop:choose-source-directory'),
  openWindow: (route, kind) => ipcRenderer.invoke('desktop:window', route, kind),
  onCommand: (callback) => { const listener = (_event, command) => callback(command); ipcRenderer.on('desktop:command', listener); return () => ipcRenderer.removeListener('desktop:command', listener); },
  notify: (payload) => ipcRenderer.invoke('desktop:notify', payload),
  setBadge: (count) => ipcRenderer.invoke('desktop:badge', count),
  revealWorkspace: () => ipcRenderer.invoke('desktop:reveal'),
  pauseSpeech: (paused) => ipcRenderer.invoke('desktop:speech-pause', paused),
  startSpeech: () => ipcRenderer.invoke('desktop:speech-start'),
  revealSpeechRecording: () => ipcRenderer.invoke('desktop:speech-reveal'),
  onSpeechTranscript: (callback) => { const listener = (_event, text) => callback(text); ipcRenderer.on('desktop:speech-transcript', listener); return () => ipcRenderer.removeListener('desktop:speech-transcript', listener); },
  onSpeechWarning: (callback) => { const listener = (_event, message) => callback(message); ipcRenderer.on('desktop:speech-warning', listener); return () => ipcRenderer.removeListener('desktop:speech-warning', listener); },
  onSpeechBackup: (callback) => { const listener = () => callback(); ipcRenderer.on('desktop:speech-backup', listener); return () => ipcRenderer.removeListener('desktop:speech-backup', listener); },
  onSpeechProgress: (callback) => { const listener = (_event, percent) => callback(percent); ipcRenderer.on('desktop:speech-progress', listener); return () => ipcRenderer.removeListener('desktop:speech-progress', listener); },
  onSpeechLevel: (callback) => { const listener = (_event, level) => callback(level); ipcRenderer.on('desktop:speech-level', listener); return () => ipcRenderer.removeListener('desktop:speech-level', listener); },
  onSpeechEnded: (callback) => { const listener = () => callback(); ipcRenderer.on('desktop:speech-ended', listener); return () => ipcRenderer.removeListener('desktop:speech-ended', listener); },
  stopSpeech: (discard = false) => ipcRenderer.invoke('desktop:speech-stop', discard),
});
